#!/usr/bin/env python3
"""Render results/candle/REPORT.md from the raw kvx-candle bench JSON files (standard library only)."""
import json
import pathlib
import sys

out = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "results/candle")
runs = sorted((out / "raw").glob("*.json"))
if not runs:
    sys.exit(f"no raw results in {out / 'raw'}")
data = [json.loads(p.read_text()) for p in runs]
ARMS = ["candle-native", "kvcachex", "kvcachex-prefix"]
MiB = 1024 * 1024


def f(x, nd=1):
    return "n/a" if x is None else f"{x:.{nd}f}"


env, model = data[0]["environment"], data[0]["model"]
lines = [
    "# Candle + KVCacheX: CPU reference integration benchmark",
    "",
    "Generated by `scripts/candle_bench.sh` from `raw/*.json`; do not edit by hand.",
    "",
    "**What this measures.** Candle 0.11.1 runs the llama2.c TinyStories model "
    f"`{model['file']}` ({model['n_layers']} layers, dim {model['dim']}, {model['n_heads']} heads, "
    f"{model['n_kv_heads']} K/V heads, context {model['context']}, f32) on the **CPU**, with two KV caches:",
    "",
    "* `candle-native`: Candle's unmodified model and cache (a contiguous tensor per layer, grown with `Tensor::cat`);",
    "* `kvcachex`: the same model, weights and Candle ops, with K/V in KVCacheX paged blocks (prefix cache off);",
    "* `kvcachex-prefix`: the same, with KVCacheX's exact prefix cache on.",
    "",
    "**Workload.** Closed loop in one process: all requests arrive at t=0, up to *C* are in flight, and each step "
    "runs **one model forward per in-flight request** (batch size 1, round-robin). This is not batched execution "
    "and not an inference server. Greedy decoding, fixed generation length. Arms are interleaved and their order "
    "rotates every repetition; numbers are medians over repetitions.",
    "",
    "* *throughput*: generated tokens / wall time of this interleaved workload;",
    "* *TTFT (queue-incl.)*: t=0 to a request's first token, **including** time waiting behind earlier prompts;",
    "* *prefill*: duration of the request's own prefill forward pass;",
    "* *ITL*: time between consecutive tokens of one request (includes other requests' steps when C > 1);",
    "* *KV peak / alloc*: K/V bytes held for live requests at peak, and bytes allocated "
    "(KVCacheX preallocates its whole block pool; Candle allocates on demand);",
    "* *Rust heap peak*: peak Rust heap growth during the run (global allocator), **not process RSS**.",
    "",
    f"Hardware: {(env.get('hardware') or env['arch']).strip().rstrip(';')} ({env['os']}/{env['arch']}), "
    f"{env.get('rustc') or 'rustc ?'}, RAYON_NUM_THREADS={env.get('rayon_num_threads')}.",
    "",
]
for d in data:
    c = d["config"]
    s = d["summary_median"]
    p = c["prompt_tokens"]
    lines += [
        f"## {c['workload']}, concurrency {c['concurrency']}",
        "",
        f"{c['requests']} requests, prompts {min(p)}–{max(p)} tokens, {c['gen_tokens']} generated tokens each, "
        f"{c['warmup']} warm-up + {c['reps']} timed repetitions per arm; KVCacheX block size {c['block_size']}, "
        f"{c['kv_blocks']} blocks.",
        "",
        "| arm | tok/s | TTFT queue-incl. p50 / p95 (ms) | prefill p50 / p95 (ms) | ITL p50 / p99 (ms) | prompt tokens computed / cached | KV peak / alloc (MiB) | Rust heap peak (MiB) | outputs = native |",
        "|---|---:|---:|---:|---:|---:|---:|---:|:---:|",
    ]
    for a in ARMS:
        m = s[a]
        lines.append(
            f"| {a} | {f(m['throughput_tok_s'])} | {f(m['ttft_queue_incl_p50_ms'])} / {f(m['ttft_queue_incl_p95_ms'])} "
            f"| {f(m['prefill_latency_p50_ms'], 2)} / {f(m['prefill_latency_p95_ms'], 2)} "
            f"| {f(m['itl_p50_ms'], 2)} / {f(m['itl_p99_ms'], 2)} "
            f"| {m['computed_prompt_tokens']:.0f} / {m['cached_prompt_tokens']:.0f} "
            f"| {f(m['peak_kv_in_use_bytes'] / MiB, 2)} / {f(m['kv_allocated_bytes'] / MiB, 2)} "
            f"| {f(m['peak_rust_heap_growth_bytes'] / MiB)} | {'yes' if m['outputs_identical_to_native'] else '**NO**'} |"
        )
    k = d["kvcachex_counters"]["kvcachex-prefix"]
    base = s["candle-native"]
    pre = s["kvcachex-prefix"]
    lines += [
        "",
        f"Prefix cache: {k['prefix_hit_blocks']} of {k['prefix_query_blocks']} full prompt blocks hit "
        f"({k['prefix_hit_tokens']} tokens), {k['prefix_revived_blocks']} revived from the free queue, "
        f"{k['evictions']} evictions, peak {k['peak_used_blocks']} of {k['total_blocks']} blocks in use.",
        f"Relative to `candle-native`: throughput ×{pre['throughput_tok_s'] / base['throughput_tok_s']:.2f} "
        f"(`kvcachex` without prefix cache ×{s['kvcachex']['throughput_tok_s'] / base['throughput_tok_s']:.2f}), "
        f"prefill p50 ×{pre['prefill_latency_p50_ms'] / base['prefill_latency_p50_ms']:.2f}, "
        f"prompt tokens computed ×{pre['computed_prompt_tokens'] / base['computed_prompt_tokens']:.2f}.",
        "",
    ]
# Summary across configurations. On `unique`, kvcachex and kvcachex-prefix do identical work (no hits),
# so their throughput spread is a direct measure of run-to-run noise in this setup.
by = {(d["config"]["workload"], d["config"]["concurrency"]): d["summary_median"] for d in data}
noise = [
    abs(m["kvcachex-prefix"]["throughput_tok_s"] / m["kvcachex"]["throughput_tok_s"] - 1)
    for (w, _), m in by.items()
    if w == "unique"
]
shared = [(c, m) for (w, c), m in sorted(by.items()) if w == "shared-prefix"]
lines += ["## Summary", ""]
if noise:
    lines.append(
        f"* **Noise floor:** on `unique` the two KVCacheX arms do identical work (0 prefix hits) yet their median "
        f"throughput differs by up to {max(noise) * 100:.0f}%. Throughput differences smaller than that are not "
        "meaningful here."
    )
for c, m in shared:
    n, k, kp = m["candle-native"], m["kvcachex"], m["kvcachex-prefix"]
    lines.append(
        f"* **shared-prefix, C={c}:** prefix reuse cut prompt tokens computed {n['computed_prompt_tokens']:.0f} → "
        f"{kp['computed_prompt_tokens']:.0f} and prefill p50 {n['prefill_latency_p50_ms']:.1f} → "
        f"{kp['prefill_latency_p50_ms']:.1f} ms; peak KV in use {n['peak_kv_in_use_bytes'] / MiB:.2f} (native) vs "
        f"{kp['peak_kv_in_use_bytes'] / MiB:.2f} MiB. Throughput {n['throughput_tok_s']:.0f} (native) / "
        f"{k['throughput_tok_s']:.0f} (kvcachex) / {kp['throughput_tok_s']:.0f} (kvcachex-prefix) tok/s."
    )
lines += [
    "* Without reuse, KVCacheX was between "
    + f"{min(m['kvcachex']['throughput_tok_s'] / m['candle-native']['throughput_tok_s'] for m in by.values()):.2f}× and "
    + f"{max(m['kvcachex']['throughput_tok_s'] / m['candle-native']['throughput_tok_s'] for m in by.values()):.2f}× "
    f"native throughput: slower on {sum(m['kvcachex']['throughput_tok_s'] < m['candle-native']['throughput_tok_s'] for m in by.values())} "
    f"of {len(by)} configurations (it adds a block-table gather on every step), by amounts "
    "comparable to the noise floor.",
    "* Every arm produced exactly the native cache's greedy tokens in every timed repetition: "
    + ("yes." if all(m[a]["outputs_identical_to_native"] for m in by.values() for a in ARMS) else "**NO**."),
    "",
]
lines += [
    "## Caveats",
    "",
    "* CPU only. Nothing here is a GPU, CUDA or T4 result, and nothing is a production-serving speedup.",
    "* Gains with the prefix cache come from **not recomputing shared prompt prefixes** (fewer prefill tokens). "
    "Candle's native cache has no cross-request reuse, so the comparison is native-without-reuse vs KVCacheX-with-reuse "
    "on a workload built to have shared prefixes; the `unique` workload shows the case with nothing to reuse.",
    "* Without reuse, KVCacheX's paged path does the same work as Candle's `Tensor::cat` cache plus a block-table "
    "gather; differences there are overhead/noise of this reference implementation, not a kernel-level claim.",
    "* KVCacheX rounds K/V to whole blocks and preallocates its pool, so its KV bytes can exceed the native cache's "
    "at low concurrency; sharing reduces blocks in use when prompts overlap.",
    "* A 15M-parameter model on one CPU process: absolute numbers are small and vary between runs "
    "(M1 P/E cores, thermal state); compare arms within one report only.",
    "",
]
(out / "REPORT.md").write_text("\n".join(lines))
print(f"wrote {out / 'REPORT.md'}")
